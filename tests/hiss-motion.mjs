import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const base=process.env.UI_TEST_BASE_URL||'http://localhost:3300';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox'],proxy:base.startsWith('https:')&&process.env.HTTPS_PROXY?{server:process.env.HTTPS_PROXY}:undefined});
const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:1000}});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/design-preview',{waitUntil:'networkidle'});
await page.evaluate(()=>document.fonts.ready);
await page.waitForTimeout(1600);
assert.equal(await page.locator('.hiss-image-stack').count(),3);
assert.equal(await page.locator('.dp-collage figcaption').count(),0);
assert.equal(await page.locator('.dp-collage svg:not(button svg)').count(),0);
assert(await page.locator('.hiss-image-layer img').evaluateAll(els=>els.every(e=>e.complete&&e.naturalWidth>0)));
const style=await page.locator('.hiss-image-stack').first().evaluate(e=>({padding:getComputedStyle(e).padding,border:getComputedStyle(e).borderWidth,shadow:getComputedStyle(e).boxShadow}));
assert.deepEqual(style,{padding:'0px',border:'0px',shadow:'none'});
await page.screenshot({path:'/workspace/work/hiss-updated-desktop.png',fullPage:true});
const time=()=>page.locator('.hiss-image-layer').first().evaluate(e=>e.getAnimations()[0]?.currentTime);
await page.getByRole('button',{name:'إيقاف الحركة',exact:true}).click();
const before=await time();await page.waitForTimeout(250);assert.equal(await time(),before,'Pause must freeze the current frame');
await page.getByRole('button',{name:'تشغيل الحركة',exact:true}).click();
await page.waitForTimeout(250);assert((await time())>before,'Resume must continue the animation');
await page.locator('.dp-last-word').scrollIntoViewIfNeeded();await page.waitForTimeout(150);
const offscreen=await time();await page.waitForTimeout(200);assert.equal(await time(),offscreen,'Offscreen animation must pause');
await page.evaluate(()=>scrollTo(0,0));await page.waitForTimeout(200);
for(const width of [390,375]){
 await page.setViewportSize({width,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:`/workspace/work/hiss-updated-phone-${width}.png`,fullPage:true});
}
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForFunction(()=>Array.from(document.querySelectorAll('.hiss-image-layer')).flatMap(e=>e.getAnimations()).length===0);
const first=await page.locator('.hiss-image-layer').first().evaluate(e=>getComputedStyle(e).transform);
assert.equal(first,'none');
await page.emulateMedia({reducedMotion:'no-preference'});
await page.getByRole('button',{name:'Toggle theme',exact:true}).click();
await page.getByRole('button',{name:'EN',exact:true}).click();
assert.equal(await page.locator('html').getAttribute('dir'),'ltr');
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:'/workspace/work/hiss-updated-dark-en.png',fullPage:true});
assert.equal(errors.length,0,errors.join('\n'));
console.log('PASS unframed images, loaded images, pause/resume, offscreen pause, reduced motion, 375/390px, dark/English, no browser errors');
await browser.close();
