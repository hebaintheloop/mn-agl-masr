import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const base=process.env.UI_TEST_BASE_URL||'http://localhost:3000';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox'],proxy:base.startsWith('https:')&&process.env.HTTPS_PROXY?{server:process.env.HTTPS_PROXY}:undefined});
const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:1000},timezoneId:'Africa/Cairo'});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/design-preview',{waitUntil:'networkidle'});
await page.evaluate(()=>document.fonts.ready);
assert(await page.locator('h1').innerText());
assert(await page.evaluate(()=>document.fonts.check('600 16px "Noto Sans Arabic"')));
console.log('Typography',await page.locator('.nf-nav button').first().evaluate(el=>({family:getComputedStyle(el).fontFamily,size:getComputedStyle(el).fontSize,spacing:getComputedStyle(el).letterSpacing})));
await page.screenshot({path:'/workspace/work/nonprofit-research/new-desktop.png',fullPage:true});
for(const width of [390,375]){
 await page.setViewportSize({width,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:`/workspace/work/nonprofit-research/new-phone-${width}.png`,fullPage:true});
}
await page.getByRole('button',{name:'فتح القائمة',exact:true}).click();
await page.locator('.nf-nav').getByRole('button',{name:'الفعاليات',exact:true}).click();
assert(await page.locator('.nf-main-heading').count()||await page.locator('h1').count());
await page.getByRole('button',{name:'تغيير المظهر',exact:true}).click();
assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
await page.getByRole('button',{name:'EN',exact:true}).click();
assert.equal(await page.locator('html').getAttribute('dir'),'ltr');
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:'/workspace/work/nonprofit-research/new-phone-dark-en.png',fullPage:true});
await page.setViewportSize({width:1440,height:1000});
await page.goto(base+'/design-preview');
await page.getByRole('link',{name:'دخول',exact:true}).click();
await page.getByRole('dialog').waitFor();
assert.equal(errors.length,0,errors.join('\n'));
console.log('PASS desktop, 390/375px, font loading, mobile menu, events, dark, English, login link, no browser errors');
await browser.close();
